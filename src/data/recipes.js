// Крепость каждого рецепта по шкале 1–5
const RECIPE_STRENGTH = {
  f1: 5,
  f2: 4,
  f3: 3,
  f4: 4,
  f5: 4,
  f6: 2,
  f7: 4,
  f8: 3,
  f9: 2,
  f10: 2,
  f11: 5,
  f12: 5,
  f13: 3,
  f14: 2,
  f15: 4,
  f16: 1,
  f17: 3,
  f18: 3,
  f19: 2,
  f20: 1,
};

/**
 * Возвращает 3 рецепта, наиболее подходящих под предпочтения пользователя.
 * @param {{ strength: number, milk: boolean, sugar: boolean }} prefs
 */
export function getRecommended(prefs) {
  const scored = ALL_RECIPES.map((r) => {
    let score = 0;

    // Молоко
    if (prefs.milk && r.category === "milk") score += 3;
    if (!prefs.milk && r.category === "espresso") score += 3;

    // Крепость: чем ближе крепость рецепта к предпочтению, тем выше балл
    const recStrength = RECIPE_STRENGTH[String(r.id)] ?? 3;
    score += Math.max(0, 3 - Math.abs(prefs.strength - recStrength));

    // Сахар → сладкие напитки
    if (prefs.sugar && ["f10", "f16", "f19", "f20"].includes(String(r.id)))
      score += 2;

    return { recipe: r, score };
  });

  return scored
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((s) => s.recipe);
}
